const localeFormats = {
  vi: "vi-VN",
  en: "en-US",
  "zh-CN": "zh-CN",
  ja: "ja-JP",
  ko: "ko-KR",
  fr: "fr-FR",
};

export function translateUserText(locale, text, values = {}) {
  let result = messages[locale]?.[text] || text;
  for (const [key, value] of Object.entries(values)) {
    result = result.replaceAll(`{${key}}`, String(value));
  }
  return result;
}

export function getLocaleFormat(locale) {
  return localeFormats[locale] || localeFormats.vi;
}
